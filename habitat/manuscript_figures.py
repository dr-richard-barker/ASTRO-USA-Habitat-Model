def _case_slices(case: str, fields, z_m: float, y_m: float | None = None):
    from .cfd.slices import load
    meta = _j(ROOT / "runs" / case / "case_meta.json")
    vol, _ = load(ROOT / "runs" / case)
    vol = vol.cell_data_to_point_data()
    for f in fields:
        vol.point_data[f] = vol.point_data[f + "Mean"]                      # time means only, never a snapshot
    lo, hi = np.array(vol.bounds[0::2]), np.array(vol.bounds[1::2])
    y = (lo[1] + hi[1]) / 2 if y_m is None else y_m
    plan = vol.slice(normal="z", origin=(0, 0, z_m)).triangulate()
    sec = vol.slice(normal="y", origin=(0, y, 0)).triangulate()
    return meta, plan, sec, y


def _tri(ax, sl, f, u, v, **kw):
    faces = sl.faces.reshape(-1, 4)[:, 1:]
    return ax.tripcolor(sl.points[:, u], sl.points[:, v], faces, kw.pop("fn", lambda a: a)(sl.point_data[f]),
                        shading="gouraud", rasterized=True, **kw)


def fig_fields() -> None:
    case = "fpm_m0_coarse_ke_tr"
    z = 1.1                                                                    # seated/standing breathing height
    meta, plan, sec, y = _case_slices(case, ["T", "dCO2", "AoA"], z)
    rows = [("T", "air temperature (°C)", lambda a: a - 273.15, "cividis"),
            ("dCO2", "CO₂ above supply air (ppm)", None, "viridis"),
            ("AoA", "age of air (s)", None, "magma")]
    fig, axs = plt.subplots(3, 2, figsize=(W, 4.6), layout="constrained")
    for r, (f, lab, fn, cmap) in enumerate(rows):
        vals = np.concatenate([plan.point_data[f], sec.point_data[f]])
        vals = fn(vals) if fn else vals
        vmin, vmax = np.percentile(vals, [1, 99])
        kw = dict(cmap=cmap, vmin=vmin, vmax=vmax, **({"fn": fn} if fn else {}))
        tc = _tri(axs[r, 0], plan, f, 0, 1, **dict(kw))
        _tri(axs[r, 1], sec, f, 0, 2, **dict(kw))
        fig.colorbar(tc, ax=axs[r, :], shrink=0.9, pad=0.01, label=lab)
    for ax in axs.flat:
        ax.set_aspect("equal"); ax.tick_params(length=2)
    for ax in axs[-1]:
        ax.set_xlabel("x from the door end (m)")
    for ax in axs[:, 0]:
        ax.set_ylabel("y (m)")
    for ax in axs[:, 1]:
        ax.set_ylabel("z (m)")
    axs[0, 0].set_title(f"(a) plan at z = {z:.1f} m")
    axs[0, 1].set_title(f"(b) section along the aisle, y = {y:.2f} m")
    _save(fig, "fig_fields.pdf")


def fig_age_sections() -> None:
    sc = _j(RC / "scenarios.json")
    cases = [("baseline", sc["baseline"], None), ("six crew (S2)", sc["scenarios"]["s2"]["case"], "s2"),
             ("half airflow (S5a)", sc["scenarios"]["s5a"]["case"], "s5a")]
    fig, axs = plt.subplots(3, 1, figsize=(W, 3.9), layout="constrained", sharex=True)
    tcs = []
    for ax, (lab, case, key) in zip(axs, cases):
        meta, _, sec, y = _case_slices(case, ["AoA"], 1.1)
        tau_n = meta["transient"]["t_flush_s"]
        rows = sc["scenarios"][key or "s2"]["rows"]["domain:AoA_s"]
        mean_age = rows["scenario"] if key else rows["base"]
        sec.point_data["age_n"] = sec.point_data["AoA"] / tau_n
        tcs.append(_tri(ax, sec, "age_n", 0, 2, cmap="magma", vmin=0, vmax=2.0))
        ax.set_aspect("equal"); ax.set_ylabel("z (m)"); ax.tick_params(length=2)
        ax.set_title(f"{lab}: air-change efficiency τₙ / (2⟨τ⟩) = {tau_n / (2 * mean_age):.2f}", loc="left")
    axs[-1].set_xlabel("x from the door end (m), section along the aisle")
    fig.colorbar(tcs[0], ax=axs, shrink=0.8, pad=0.01, label="local age of air / nominal time constant τₙ")
    _save(fig, "fig_age_sections.pdf")


