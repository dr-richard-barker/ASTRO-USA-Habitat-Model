def tab_runs() -> None:
    rows = []
    for case, lab in RUNS:
        g, m = _j(RC / f"{case}_gates.json"), _j(ROOT / "runs" / case / "case_meta.json")
        if not (g and m):
            continue
        tr = m["transient"]
        tau = tr["t_flush_s"]
        t0, t1 = g["steady"]["window_s"] if "window_s" in g["steady"] else (tr["avg_from_s"], g["steady"]["time_s"])
        err = max(abs(v) for v in g["rel_err"].values())
        model = {"kEpsilon": "$k$--$\\varepsilon$", "kOmegaSST": "SST $k$--$\\omega$"}[m.get("turbulence_model", "kOmegaSST")]
        stat = "yes" if g["gates"]["steady"] else "no"
        cells = f"{g['cells']:,}".replace(",", "{,}")
        rows.append(f"{lab} & {model} & {cells} & {1000 * m['physics']['Q_m3_s']:.0f} & {tau:.0f} & "
                    f"{t0 / tau:.1f}--{t1 / tau:.1f} & {100 * err:.2f} & {stat} & {'pass' if g['pass'] else 'fail'} \\\\")
    _tex("tab_runs.tex", "\\begin{tabular}{llrrrcrcc}\n\\toprule\nCase & Turbulence & Cells & $Q$ (L\\,s$^{-1}$) & "
         "$\\tau_n$ (s) & Averaged ($\\tau_n$) & Max.\\ balance error (\\%) & Stationary & Gates \\\\\n\\midrule\n"
         + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def tab_gci() -> None:
    gj = _j(RC / "gci_m0.json")
    noise = gci_noise([f"fpm_m0_{m}_tr" for m in gj["meshes"]], RC)
    hs = {k: d["h_m"] * 1000 for k, d in gj["meshes"].items()}
    lad = gj["ladder"]
