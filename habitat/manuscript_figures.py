def fig_drawing() -> None:
    """The general-arrangement sheet (plan + elevations), cropped to the drawing (footer note dropped)."""
    import pymupdf
    src = ROOT / "results" / "drawings" / "FPM_GA.pdf"
    doc = pymupdf.open(src)
    page = doc[0]
    foot = min((b[1] for b in page.get_text("blocks") if b[4].startswith("ASTRO-USA Mini-Hab")), default=page.rect.y1)
    pix = page.get_pixmap(dpi=72, clip=pymupdf.Rect(page.rect.x0, page.rect.y0, page.rect.x1, foot - 2))
    a = np.frombuffer(pix.samples, np.uint8).reshape(pix.height, pix.width, pix.n)[..., :3]
    ys, xs = np.nonzero((a < 245).any(axis=2))                                   # inked pixels (72 dpi = 1 px per pt)
    box = pymupdf.Rect(xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)
    page.set_cropbox((box + (-4, -4, 4, 4)) & page.mediabox)
    FIG.mkdir(parents=True, exist_ok=True)
    doc.set_metadata({})
    doc.save(FIG / "fig_drawing.pdf", garbage=3, deflate=True, no_new_id=True)
    print("wrote manuscript/figures/fig_drawing.pdf")


