def tab_scenarios() -> None:
    sc = _j(RC / "scenarios.json")
    keys = [k for k in ("s2", "s5a") if k in sc["scenarios"]]
    base_rows = sc["scenarios"][keys[0]]["rows"]
    rows = []
    for q in ("domain:T_excess_K", "domain:dCO2_ppm", "domain:AoA_s", "occupied:U_mean_m_s", "crew_1:dCO2_ppm",
              "crew_2:dCO2_ppm", "nft_canopy:T_excess_K"):
        fmt = "{:.0f}" if abs(base_rows[q]["base"]) >= 20 else "{:.2f}"
        cells = [fmt.format(base_rows[q]["base"])]
        for k in keys:
            r = sc["scenarios"][k]["rows"][q]
            cells.append(f"{fmt.format(r['scenario'])} ($\\times${r['ratio']:.2f})")
        rows.append(f"{QTY[q]} & " + " & ".join(cells) + " \\\\")
    ace = []
    for case, key in ((sc["baseline"], None), *((sc["scenarios"][k]["case"], k) for k in keys)):
        tau = _j(ROOT / "runs" / case / "case_meta.json")["transient"]["t_flush_s"]
        a = sc["scenarios"][key or keys[0]]["rows"]["domain:AoA_s"]
        ace.append(f"{tau / (2 * (a['scenario'] if key else a['base'])):.2f}")
    rows.append("Air-change efficiency $\\tau_n/(2\\langle\\tau\\rangle)$ & " + " & ".join(ace) + " \\\\")
    flows = [f"{1000 * sc['baseline_Q_m3_s']:.0f}"] + [f"{1000 * sc['scenarios'][k]['Q_m3_s']:.0f}" for k in keys]
    heats = [f"{sc['baseline_heat_W']:.0f}"] + [f"{sc['scenarios'][k]['heat_W']:.0f}" for k in keys]
    head = ("Quantity & Baseline & S2: six crew & S5a: half airflow \\\\\n"
            f"Supply airflow (L\\,s$^{{-1}}$) & {' & '.join(flows)} \\\\\nHeat load (W) & {' & '.join(heats)} \\\\")
    _tex("tab_scenarios.tex", "\\begin{tabular}{l" + "r" * (len(keys) + 1) + "}\n\\toprule\n" + head + "\n\\midrule\n"
         + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def tab_sensors(n: int = 5) -> None:
    sp = _j(RC / "sensor_placement.json")
    rows = []
    for k, r in enumerate(sp["ranked"][:n], 1):
        wall = "attic partition" if "attic" in r["wall"] else ("battery / work wall" if "y=0" in r["wall"] else "hydroponic wall")
        along = f"$y={r['y_m']:.2f}$" if "attic" in r["wall"] else f"$x={r['x_m']:.2f}$"
        rows.append(f"{k} & {wall} & {along} & {r['z_m']:.1f} & {r['worst_T']:.2f} & {r['worst_dCO2']:.1f} & {r['clearance_m']:.2f} \\\\")
    _tex("tab_sensors.tex", "\\begin{tabular}{rllrrrr}\n\\toprule\nRank & Wall & Along wall (m) & Height (m) & "
         "Worst $|\\Delta T|$ (K) & Worst $|\\Delta$CO\\textsubscript{2}$|$ (\\%) & Clearance (m) \\\\\n\\midrule\n"
         + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-fields", action="store_true", help="skip figures that read OpenFOAM fields from runs/")
    a = ap.parse_args(argv)
    fig_render(); fig_drawing(); fig_annex20(); fig_s3()
    if a.no_fields or not (ROOT / "runs" / "fpm_m0_coarse_ke_tr").exists():
        print("field figures skipped (no local run directories); the committed figure files are kept")
    else:
        fig_fields(); fig_age_sections(); fig_offgas()
    tab_ledger(); tab_runs(); tab_gci(); tab_annex20(); tab_scenarios(); tab_sensors()


if __name__ == "__main__":
    main()
