def tab_ledger() -> None:
    full = Ledger()
    kinds = [k for k in ("specified", "derived", "user_supplied", "measured", "assumed")
             if any(r["kind"] == k for r in full.records.values())]
    head = {"specified": "Quoted", "derived": "Derived", "user_supplied": "User-supplied", "measured": "Measured",
            "assumed": "Assumed"}
    rows, tot = [], {k: 0 for k in ["n", *kinds, "ask"]}
    for f in sorted((ROOT / "ledger").glob("*.yaml")):
        L = Ledger([f])
        n = {k: sum(1 for r in L.records.values() if r["kind"] == k) for k in kinds}
        n["ask"] = sum(1 for r in L.records.values() if r["kind"] == "assumed" and r.get("ask_team"))
        n["n"] = len(L.records)
        name = f.stem.replace("_", "\\_")
        rows.append(f"\\texttt{{{name}}} & " + " & ".join(str(n[k]) for k in ["n", *kinds, "ask"]) + " \\\\")
        for k in tot:
            tot[k] += n[k]
    assert tot["n"] == len(full.records), "per-file record counts do not add up to the whole ledger"
    _tex("tab_ledger.tex", "\\begin{tabular}{l" + "r" * (len(kinds) + 2) + "}\n\\toprule\nLedger file & Records & "
         + " & ".join(head[k] for k in kinds) + " & Ask team \\\\\n\\midrule\n" + "\n".join(rows)
         + "\n\\midrule\nTotal & " + " & ".join(str(tot[k]) for k in ["n", *kinds, "ask"])
         + " \\\\\n\\bottomrule\n\\end{tabular}\n")


