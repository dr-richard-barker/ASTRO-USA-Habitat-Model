PDF_META = {"CreationDate": None, "ModDate": None, "Producer": None}       # byte-identical rebuilds


def _j(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def _save(fig, name: str) -> Path:
    FIG.mkdir(parents=True, exist_ok=True)
    p = FIG / name
    fig.savefig(p, metadata=PDF_META)
    plt.close(fig)
    print("wrote", p.relative_to(ROOT))
    return p


def _tex(name: str, body: str) -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / name).write_text("% generated by habitat/manuscript_figures.py from the result files; do not edit by hand\n" + body)
    print("wrote", (TAB / name).relative_to(ROOT))


def _grid(ax):
    ax.grid(True, color=GRID, lw=0.5)
    ax.set_axisbelow(True)


