"""One-page brief for the ASTRO-USA team lead, generated from the result files (never typed numbers).

    uv run python -m habitat.brief          -> TEAM_BRIEF.md

States what the model is, what it has found so far (each with its main caveat), and the few answers that unblock the
most work. Sections whose result file is missing or failed its gates are left out rather than guessed.
"""
from __future__ import annotations

import json

from . import ROOT
from .provenance import Ledger


def _j(rel: str):
    p = ROOT / rel
    return json.loads(p.read_text()) if p.exists() else None


def main() -> None:
    L = Ledger()
    m0 = _j("results/cfd/fpm_m0_coarse_tr_gates.json")
    s6 = _j("results/cfd/fpm_s6_coarse_ke_tr_siting.json")       # k-epsilon run once it passes, else kOmegaSST
    if not (s6 and s6.get("pass")):
        s6 = _j("results/cfd/fpm_s6_coarse_tr_siting.json")
    lb = _j("results/light_budget.json")
    s3 = _j("results/s3_hvac_off.json")
    sp = _j("results/cfd/sensor_placement.json")
    gci = _j("results/cfd/gci_m0.json")
    A = L.assumptions()
    out = [f"<!-- generated by habitat/brief.py from the result files (ledger {L.digest()}); do not edit by hand -->\n\n",
           "# ASTRO-USA Food Production Module: digital model, first findings and questions\n\n",
           "**What it is.** A parametric model of the FPM built from ICES-2026-251. One sourced ledger of dimensions "
           "and loads drives engineering CAD, airflow CFD (OpenFOAM) and a browser 3-D/VR walk-through. Every value "
           f"is either quoted from a source or a declared assumption: {len(A)} of {len(L.records)} values are still "
           "assumptions, and most can only be replaced by the team. The repository is private until the team "
           "agrees to a public release.\n\n",
           "## First findings (screening level: coarse mesh, stand-in HVAC, insulated walls)\n\n"]
    if m0 and m0.get("pass"):
        out.append(f"- **Airflow baseline.** The time-averaged run ({m0['cells']:,} cells) closes its heat, CO₂, "
                   "water-vapour and age-of-air balances within 1 %. A cold supply jet from the attic partition "
                   "drops to the floor a few metres into the room; the two crew plumes are the warm, high-CO₂ spots. "
                   "The absolute numbers depend on the real attic unit (unknown).\n")
        if gci:
            ok = gci.get("all_gates_pass")
            sp = {k: abs(r["phi_fine"] - r["phi_coarse"]) / abs(r["phi_fine"]) * 100 for k, r in gci["gci"].items()
                  if r["phi_fine"] and "U_" not in k}
            dom = max(v for k, v in sp.items() if k.startswith("domain:"))
            loc = max(v for k, v in sp.items() if not k.startswith("domain:"))
            out.append(f"- **Mesh sensitivity.** On three meshes ({'all passing' if ok else 'not all passing'} their "
                       f"checks), room-wide averages change by at most {dom:.0f} %, local values near the crew by up "
                       f"to {loc:.0f} %: the room-scale picture is robust, single-point values need the finer mesh "
                       "(checked with the earlier turbulence model; see the validation note).\n")
    sc = _j("results/cfd/scenarios.json")
    if sc and "s2" in sc.get("scenarios", {}):
        r = sc["scenarios"]["s2"]["rows"]
        out.append(f"- **Six crew at once.** Room CO₂ rises about {r['domain:dCO2_ppm']['scenario']:.0f} ppm above the "
                   f"supply air (×{r['domain:dCO2_ppm']['ratio']:.1f} the two-crew case) and the room runs "
                   f"{r['domain:T_excess_K']['scenario']:.1f} K above it (two crew: {r['domain:T_excess_K']['base']:.1f} K), "
                   "with the placeholder HVAC.\n")
    if sc and "s5a" in sc.get("scenarios", {}):
        r = sc["scenarios"]["s5a"]["rows"]
        out.append(f"- **Half the airflow.** The room's temperature rise grows ×{r['domain:T_excess_K']['ratio']:.2f}, CO₂ "
                   f"×{r['domain:dCO2_ppm']['ratio']:.2f} and the age of air ×{r['domain:AoA_s']['ratio']:.2f} (perfect "
                   "mixing would give ×2): mixing gets worse at low flow, so the HVAC unit's airflow matters. (Double "
                   "airflow did not settle within its run and is not reported.)\n")
    mc = _j("results/cfd/model_compare.json")
    if mc:
        sm = mc["summary"]
        out.append(f"- **Turbulence model.** Re-running the baseline with the better-validated model changes room-wide "
                   f"averages by at most {sm['domain_max_pct']:.0f} % and single points by up to "
                   f"{sm['local_max_pct']:.0f} %: the room-scale findings stand.\n")
    a20 = _j("results/cfd/annex20.json")
    if a20:
        def rng(model):
            v = [e["rms"] for m, r in a20["runs"].items() if m.startswith(model) for e in r["errors"].values()]
            return f"{min(v):.2f}–{max(v):.2f}"
        out.append(f"- **Validation.** Against laser measurements of a standard ventilated-room benchmark (IEA "
                   f"Annex 20, isothermal), standard k-ε errs by {rng('kEpsilon')} of the inlet velocity and the "
                   f"model used first (kOmegaSST) by {rng('kOmegaSST')}, so the airflow model now uses k-ε.\n")
    if s6 and s6.get("pass"):
        r = s6["return_ppm"]
        lo, hi = f"{min(r.values()):.1f}", f"{max(r.values()):.1f}"
        offgas = lo if lo == hi else f"{lo}–{hi}"
        can = s6["rows"]["zone:nft_canopy"]["nft_wall"]                 # canopy-zone excess, NFT-wall route
        crew = ""
        if m0 and "return_dCO2_halves_ppm" in m0.get("steady", {}):
            c = sum(m0["steady"]["return_dCO2_halves_ppm"]) / 2          # crew-generated excess, well mixed (return)
            crew = f", against about {c:.0f} ppm from the two working crew mixed the same way (baseline run)"
        out.append(f"- **Biomanufacturing off-gas.** The bioreactor rack's CO₂ (a placeholder planning rate) adds about "
                   f"{offgas} ppm when mixed through the room, whichever of three routes it takes{crew}. Even piped "
                   f"to the hydroponic wall it raises the canopy zone by only {can:.1f} ppm, so with current "
                   "assumptions it is not a useful CO₂ supply for the plants.\n")
    nav = _j("results/nav.json")
    if nav and nav.get("pass"):
        a, b2 = (n.replace("_", " ").replace("nft", "NFT") for n in nav["min_clear_aisle_between"])
        out.append(f"- **Space to move.** The narrowest clear aisle is {nav['min_clear_aisle_m']:.2f} m "
                   f"({nav['min_clear_aisle_at_x_m']:.1f} m from the door, between the {a} and the {b2}); keeping "
                   f"{nav['agent_radius_m']:.2f} m clear of "
                   f"equipment leaves {nav['walkable_area_m2']:.1f} m² of the {nav['floor_area_m2']:.1f} m² floor to walk "
                   "on. A layout figure, not a code check; worth a look for six crew at once.\n")
    if lb:
        a = next(v for k, v in lb["areas"].items() if k.startswith("NFT wall"))
        i = lb["inputs"]
        out.append(f"- **Lighting vs power budget.** If the stated {i['load_max_W']:.0f} W maximum draw includes the "
                   f"grow lights, the NFT wall cannot exceed about {a['ppf_max_all_450W_to_light']:.0f} µmol/m²·s even "
                   f"with every watt going to light at the best LED efficacy reported ({i['fixture_umol_J']:g} µmol/J). "
                   f"NASA's lettuce crop model starts at {i['mec_ppf_range'][0]:.0f}; reaching it needs about "
                   f"{a['power_for_mec_minimum_W']:.0f} W for lights alone. Until the lighting is known, the plants "
                   "are not coupled into the airflow model.\n")
    if s3:
        sealed = {c["crew"]: c["hours_to_limit"] for c in s3["cases"] if c["ach"] == 0}
        out.append(f"- **HVAC failure, door shut.** CO₂ reaches OSHA's {s3['limit_ppm']:.0f} ppm limit (an 8-hour "
                   f"average) in about {sealed.get(6):.1f} h with six crew and {sealed.get(2):.1f} h with two, if the "
                   "container is airtight; modest leakage changes this a lot. The same applies with the unit running "
                   "if it only recirculates room air.\n")
    if sp and sp.get("ranked"):
        best = next((r for r in sp["ranked"] if r.get("clearance_m", 0) >= 1.0), sp["ranked"][0])
        wall = best["wall"].split("(")[1].rstrip(")") + " wall" if "(" in best["wall"] else best["wall"]
        where = (f"the {wall}, "
                 + (f"{best['y_m']:.2f} m along" if "attic" in best["wall"] else f"{best['x_m']:.2f} m from the door")
                 + f", {best['z_m']:.1f} m high")
        out.append(f"- **Where to put a room sensor.** Of the wall positions tested, one at {where} reads within "
                   f"{best['worst_T']:.2f} K and {best['worst_dCO2']:.1f} % of the crew-zone average "
                   + ("in the baseline run" if len(sp["cases"]) == 1 else f"in all {len(sp['cases'])} runs")
                   + ", and is over 1 m from any growing system. Plant gas exchange is not modelled yet, so "
                   "positions near the plants were excluded.\n")
    out.append("\n## The answers that unblock the most\n\n"
               "1. **Grow lights:** fixture model, count, wattage, photoperiod and the light level at the canopy; "
               "and whether they are inside the 450 W / 8 kWh budget.\n"
               "2. **Attic HVAC:** make and model, airflow, grille positions, and whether it brings in outdoor air.\n"
               "3. **Container leakage:** a CO₂ decay measurement with the door shut gives the air-change rate.\n"
               "4. **The Fusion 360 model** behind Figures 4–5 (STEP export), to check our geometry against yours.\n"
               "5. **Consent and credit** for releasing the model publicly, and the credit line you want.\n\n"
               "The full list, with every assumption the team can replace, is in TEAM_INPUTS.md.\n")
    (ROOT / "TEAM_BRIEF.md").write_text("".join(out))
    print((ROOT / "TEAM_BRIEF.md").read_text())


if __name__ == "__main__":
    main()
